"""
Secure Media and Document Download Views with Signed URL / Media Token and JWT Token support.
Ensures document files are accessible to authenticated users while strictly preventing unauthorized access.
"""
import os
import mimetypes
import logging
from django.conf import settings
from django.http import FileResponse, Http404, JsonResponse
from django.core.files.storage import default_storage

logger = logging.getLogger(__name__)
from django.core.signing import TimestampSigner, BadSignature, SignatureExpired
from rest_framework.views import APIView
from rest_framework.permissions import IsAuthenticated, AllowAny
from rest_framework_simplejwt.authentication import JWTAuthentication
from rest_framework_simplejwt.tokens import AccessToken
from django.contrib.auth import get_user_model
from rest_framework import status
from rest_framework.response import Response

signer = TimestampSigner(salt="utc-media-token")
MEDIA_TOKEN_MAX_AGE_SECONDS = 900  # 15 minutes


def generate_media_token(user_id, file_path):
    """Generate a signed, tamper-proof token for media download with 15-minute validity."""
    norm_path = os.path.normpath(file_path).replace("\\", "/")
    value = f"{user_id}:{norm_path}"
    return signer.sign(value)


def verify_media_token(token, file_path):
    """
    Verify signed media token.
    Returns user_id if valid, None if invalid or expired.
    """
    norm_path = os.path.normpath(file_path).replace("\\", "/")
    try:
        unsigned_value = signer.unsign(token, max_age=MEDIA_TOKEN_MAX_AGE_SECONDS)
        parts = unsigned_value.split(":", 1)
        if len(parts) == 2 and parts[1] == norm_path:
            return parts[0]
    except (BadSignature, SignatureExpired):
        return None
    return None


def verify_access_token_or_media_token(token, file_path):
    """
    Verify authentication token passed via query parameter (?token=...):
    1. Supports JWT Access Token (passed from frontend client, starts with eyJ...)
    2. Supports Django TimestampSigner Media Token (generated by GetSignedMediaUrlAPIView)
    Returns: User instance or user_id if valid, None otherwise.
    """
    if not token or not isinstance(token, str):
        return None

    cleaned_token = token.strip()

    # 1. Check if token is a standard JWT Bearer Token (starts with eyJ)
    if cleaned_token.startswith("eyJ"):
        try:
            access = AccessToken(cleaned_token)
            uid = access.get("user_id")
            if uid:
                User = get_user_model()
                user = User.objects.filter(id=uid, is_active=True).first()
                if user:
                    return user
        except Exception:
            pass

    # 2. Check if token is a signed Media Token (TimestampSigner)
    user_id = verify_media_token(cleaned_token, file_path)
    if user_id:
        return user_id

    # 3. Fallback: try parsing as JWT even if it doesn't match standard prefix
    try:
        access = AccessToken(cleaned_token)
        uid = access.get("user_id")
        if uid:
            User = get_user_model()
            user = User.objects.filter(id=uid, is_active=True).first()
            if user:
                return user
    except Exception:
        pass

    return None


def is_safe_relative_path(rel_path):
    """Ensure path contains no directory traversal, null bytes, or absolute path components."""
    if not rel_path or not isinstance(rel_path, str):
        return False
    if "\x00" in rel_path:
        return False
    norm = os.path.normpath(rel_path).replace("\\", "/")
    if norm.startswith("..") or norm.startswith("/") or os.path.isabs(norm):
        return False
    parts = norm.split("/")
    if ".." in parts:
        return False
    return True


def check_attachment_access(user, safe_rel_path):
    """
    Check if the authenticated user is authorized to access a chat attachment.
    - Superuser, staff, admin, committee: full access.
    - If file belongs to SupervisorGroupChatMessage:
        User must be the supervisor OR an assigned student of that supervisor.
    - If file belongs to ChatRoom:
        User must be the student OR the supervisor in that chat room.
    - General shared files (templates, outlines, news): allowed for authenticated users.
    """
    if not user or not user.is_authenticated:
        return False

    user_type = getattr(user, "user_type", "")
    if getattr(user, "is_superuser", False) or getattr(user, "is_staff", False) or user_type in ["admin", "committee"]:
        return True

    base_name = os.path.basename(safe_rel_path)

    try:
        from .models import SupervisorGroupChatMessage
        group_msg = SupervisorGroupChatMessage.objects.filter(
            attachment__icontains=base_name
        ).first()
        if group_msg:
            from .views_supervisor_group_chat import get_user_supervisor
            user_sup = get_user_supervisor(user)
            if user_sup and user_sup.id == group_msg.supervisor_id:
                return True
            return False
    except Exception:
        pass

    try:
        from .models import ChatRoom
        chat_room_msg = ChatRoom.objects.filter(
            attachment__icontains=base_name
        ).select_related("student__user", "supervisor__user").first()
        if chat_room_msg:
            if (chat_room_msg.student and chat_room_msg.student.user_id == user.id) or \
               (chat_room_msg.supervisor and chat_room_msg.supervisor.user_id == user.id):
                return True
            return False
    except Exception:
        pass

    return True


class GetSignedMediaUrlAPIView(APIView):
    """
    Endpoint for authenticated clients to obtain a short-lived Signed URL / Media Token
    for downloading or opening files in browser tabs.
    """
    authentication_classes = [JWTAuthentication]
    permission_classes = [IsAuthenticated]

    def get(self, request):
        file_path = request.query_params.get("file_path", "").strip().lstrip("/")
        if not file_path:
            return Response({"detail": "Thiếu tham số file_path."}, status=status.HTTP_400_BAD_REQUEST)

        # Sanitize file path
        norm_path = os.path.normpath(file_path).replace("\\", "/")
        if norm_path.startswith("..") or os.path.isabs(norm_path):
            return Response({"detail": "Đường dẫn tệp không hợp lệ."}, status=status.HTTP_400_BAD_REQUEST)

        token = generate_media_token(request.user.id, norm_path)
        download_url = f"/api/media/download/{norm_path}?token={token}"

        return Response({
            "file_path": norm_path,
            "signed_url": download_url,
            "token": token,
            "expires_in": MEDIA_TOKEN_MAX_AGE_SECONDS,
        }, status=status.HTTP_200_OK)


class SecureMediaDownloadView(APIView):
    """
    Unified secure media download handler:
    1. Rejects unauthenticated/anonymous requests without token.
    2. Accepts:
       - Header 'Authorization: Bearer <jwt_token>'
       - Query parameter '?token=<jwt_access_token>' (from browser download / window.open)
       - Query parameter '?token=<signed_media_token>'
    3. Verifies file path boundaries and streams the file securely.
    """
    authentication_classes = [JWTAuthentication]
    permission_classes = [AllowAny]

    subfolder = None  # Can be overridden by subclasses or url kwargs

    def get(self, request, file_path=None, filename=None):
        raw_path = file_path or filename or ""
        if self.subfolder and filename:
            raw_path = os.path.join(self.subfolder, filename)
        
        # Normalize and sanitize file path
        safe_rel_path = os.path.normpath(raw_path.lstrip("/")).replace("\\", "/")
        if not is_safe_relative_path(raw_path) or safe_rel_path.startswith("..") or os.path.isabs(safe_rel_path):
            return Response({"detail": "Đường dẫn không hợp lệ."}, status=status.HTTP_400_BAD_REQUEST)

        # Strip redundant leading "media/" prefix if present in URL
        if safe_rel_path.startswith("media/"):
            safe_rel_path = safe_rel_path[len("media/"):]

        # 1. Check Authentication:
        # Either request.user is authenticated (JWT in Authorization header) OR query token is valid
        is_authenticated = request.user and request.user.is_authenticated

        if not is_authenticated:
            # Check for ?token= or ?access_token= query parameter
            query_token = request.query_params.get("token") or request.query_params.get("access_token")
            if query_token:
                auth_result = verify_access_token_or_media_token(query_token, safe_rel_path)
                if auth_result:
                    is_authenticated = True
                    if hasattr(auth_result, "is_authenticated"):
                        request.user = auth_result
                else:
                    return Response(
                        {"detail": "Liên kết tải tệp hoặc mã xác thực (Media Token) đã hết hạn hoặc không hợp lệ. Vui lòng đăng nhập lại."},
                        status=status.HTTP_401_UNAUTHORIZED
                    )

        if not is_authenticated:
            return Response(
                {"detail": "Yêu cầu xác thực phiên đăng nhập. Vui lòng đăng nhập để tải tài liệu."},
                status=status.HTTP_401_UNAUTHORIZED
            )

        # 3. Check Attachment Access Permissions (prevent unauthorized access to other chats)
        if not check_attachment_access(request.user, safe_rel_path):
            return Response(
                {"detail": "Bạn không có quyền truy cập tệp tin này."},
                status=status.HTTP_403_FORBIDDEN
            )

        # 4. Locate File in Storage (Cloudflare R2 / AWS S3 / Local Storage)
        base_name = os.path.basename(safe_rel_path)

        candidate_storage_keys = [
            safe_rel_path,
            f"chat_attachments/{base_name}",
            f"documents/{base_name}",
            f"doc_templates/{base_name}",
            f"outlines/{base_name}",
            f"task_deliverables/{base_name}",
            f"weekly_reports/{base_name}",
            f"deferral_evidence/{base_name}",
            f"media/{safe_rel_path}",
            f"media/chat_attachments/{base_name}",
        ]

        found_file_handle = None
        storage_error = None

        for key in candidate_storage_keys:
            try:
                if default_storage.exists(key):
                    found_file_handle = default_storage.open(key, "rb")
                    break
            except Exception as e:
                storage_error = e
                # Fall through to try other keys or local filesystem fallback
                pass

        # Local filesystem fallback (supports seed data / repository templates committed on disk)
        if not found_file_handle:
            candidate_paths = [
                os.path.abspath(os.path.join(settings.MEDIA_ROOT, safe_rel_path)),
                os.path.abspath(os.path.join(settings.BASE_DIR, safe_rel_path)),
                os.path.abspath(os.path.join(settings.BASE_DIR, "media", safe_rel_path)),
                os.path.abspath(os.path.join(settings.MEDIA_ROOT, "chat_attachments", base_name)),
                os.path.abspath(os.path.join(settings.BASE_DIR, "media", "chat_attachments", base_name)),
                os.path.abspath(os.path.join(settings.BASE_DIR, "chat_attachments", base_name)),
                os.path.abspath(os.path.join(settings.MEDIA_ROOT, "documents", base_name)),
                os.path.abspath(os.path.join(settings.BASE_DIR, "documents", base_name)),
                os.path.abspath(os.path.join(settings.MEDIA_ROOT, "doc_templates", base_name)),
                os.path.abspath(os.path.join(settings.BASE_DIR, "doc_templates", base_name)),
                os.path.abspath(os.path.join(settings.MEDIA_ROOT, "outlines", base_name)),
                os.path.abspath(os.path.join(settings.BASE_DIR, "outlines", base_name)),
            ]
            for cand in candidate_paths:
                if os.path.exists(cand) and os.path.isfile(cand):
                    try:
                        found_file_handle = open(cand, "rb")
                        break
                    except Exception:
                        pass

        if not found_file_handle:
            if storage_error and getattr(settings, 'USE_S3', False):
                logger.warning(f"Storage backend error while accessing '{safe_rel_path}': {storage_error}")
                return Response(
                    {"detail": "Dịch vụ lưu trữ tệp tin tạm thời không khả dụng. Vui lòng thử lại sau."},
                    status=status.HTTP_503_SERVICE_UNAVAILABLE
                )
            return Response(
                {"detail": f"Tệp tin '{base_name}' không tồn tại hoặc đã bị xóa."},
                status=status.HTTP_404_NOT_FOUND
            )

        # 5. Stream File with Attachment Headers & CORS
        download_filename = base_name
        content_type, _ = mimetypes.guess_type(base_name)
        is_inline = request.GET.get("inline") == "1" or request.GET.get("preview") == "1"
        response = FileResponse(
            found_file_handle,
            as_attachment=not is_inline,
            filename=download_filename,
            content_type=content_type or "application/octet-stream"
        )
        response["Cache-Control"] = "private, no-cache, no-store, must-revalidate"
        response["Pragma"] = "no-cache"
        response["Access-Control-Allow-Origin"] = "*"
        response["Access-Control-Expose-Headers"] = "Content-Disposition, Content-Length"
        return response


class DocumentSecureDownloadView(SecureMediaDownloadView):
    """Secure download for documents/ subfolder."""
    subfolder = "documents"


class TemplateSecureDownloadView(SecureMediaDownloadView):
    """Secure download for doc_templates/ subfolder."""
    subfolder = "doc_templates"
